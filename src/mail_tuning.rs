//! 邮件排版的可调阈值，集中一处方便用回归集标定。
//!
//! **不要把这些数字散回各模块。** 它们是「照着真实邮件语料调出来的经验值」，
//! 分散在解析、渲染、清洗三处时，改一个就会在别处出现不一致的行为。
//!
//! 标定依据：`tests/fixtures/mail` 下 100 封合成语料（A 通栏轻 HTML / B 居中单卡 CTA /
//! C 深色 hero / D 中文事务 / E 混排多栏，各 20 封），由
//! `cargo test --test mail_fixtures -- --ignored --nocapture` 输出分布。
//! 调整任何一个常量后必须重跑 `cargo test --test mail_fixtures`，
//! 断言守住「布局表不许被当成数据表」「单行表格必须摊平」这两条底线。

// ---------------------------------------------------------------------------
// 表格：数据表 vs 布局表
// ---------------------------------------------------------------------------

/// 多于此列数的表格一律当布局表摊平。
///
/// 真实营销邮件的外层骨架常有 5~12 列（左右留白 + 内容 + 页脚），
/// 画成 Grid 会把正文挤成中间窄列——这正是最早那批「竖排窄列」截图的成因。
pub const MAX_DATA_COLUMNS: usize = 4;

/// 单元格文字长于此值即认为是「一段文章」而不是「一个字段」。
/// 布局表格的格子里常塞整段文案，数据表格每格只有几个词。
pub const MAX_DATA_CELL_CHARS: usize = 30;

/// 一行内「短标签」的最大格数：不超过这个数且每格都很短时，按一行合并成同一条文字，
/// 读起来像 `项目 1    ¥ 12.00` 这样的明细行，而不是拆成两段。
pub const SHORT_LABEL_CELLS: usize = 4;

/// 短标签的字符上限（见上）。
pub const SHORT_LABEL_CHARS: usize = 12;

/// 少于两行的表格一定是整页包裹器，画网格没有任何对齐价值。
pub const MIN_DATA_ROWS: usize = 2;

// ---------------------------------------------------------------------------
// 背景色
// ---------------------------------------------------------------------------

/// 低于这个 alpha 的背景视为透明。
pub const BACKGROUND_MIN_ALPHA: u8 = 8;

/// 亮于此值的背景（近白）在深色界面上只会变成脏灰块，直接丢弃。
pub const BACKGROUND_MAX_LUMA: f32 = 238.0;

/// 暗于此值且几乎没有饱和度的背景同理（纯黑骨架底色）。
pub const BACKGROUND_MIN_LUMA: f32 = 22.0;

/// 饱和度低于此值的中性灰不承载语义，丢弃。
pub const BACKGROUND_MIN_SATURATION: f32 = 22.0;

// ---------------------------------------------------------------------------
// 图片
// ---------------------------------------------------------------------------

/// 任一边不超过这个像素数的图当作追踪像素 / 分隔符，不再占位。
/// 邮件里常见 1×1 埋点与 1×N 的透明间隔条。
pub const TRACKING_PIXEL_MAX_PX: f32 = 2.0;

// ---------------------------------------------------------------------------
// 置信度
// ---------------------------------------------------------------------------

/// 低于这个分数就在阅读窗口提示「改用查看完整排版」。
///
/// 标定结果（100 封语料，`corpus_report`）：A 100、B 100、C 96–100、D 94、E 88–94。
/// 也就是说这条阈值**故意压在整批回归语料之下**：正常邮件不会看到提示，
/// 只有出现多个真 Grid 表格 + flex/绝对定位 + 背景图叠加时才会触发。
/// 提高它会让「排版其实还行」的邮件也被劝去完整视图，属于倒退。
pub const CONFIDENCE_HINT: u8 = 62;

/// 一个真的会被画成 Grid 的多列表格扣多少分。
pub const LOSS_PER_GRID_TABLE: u32 = 6;
/// 单个 CSS 特征的扣分（出现次数另有上限）。
pub const LOSS_FLEX: u32 = 6;
pub const LOSS_GRID: u32 = 6;
pub const LOSS_ABSOLUTE: u32 = 6;
pub const LOSS_FIXED: u32 = 6;
pub const LOSS_BACKGROUND_IMAGE: u32 = 4;
pub const LOSS_FLOAT: u32 = 2;
pub const LOSS_IFRAME: u32 = 10;
pub const LOSS_FORM: u32 = 8;

/// 每种特征最多计多少次，避免一封超长邮件被扣穿。
pub const LOSS_COUNT_CAP: u32 = 8;
/// iframe / form 更危险，单独用更小的上限。
pub const LOSS_RARE_CAP: u32 = 4;
/// 图片数量超过这个阈值后每张扣 1 分（图片多了阅读节奏会变差）。
pub const IMAGE_SOFT_LIMIT: u32 = 4;
/// 总分下限：再复杂的邮件也不显示 0 分，那只会让用户困惑。
pub const CONFIDENCE_FLOOR: u32 = 15;
/// 最大扣分：留一点余量，避免复杂邮件永远贴着地板。
pub const CONFIDENCE_LOSS_CAP: u32 = 85;
